// ---------------------------------------------------------------------------
// Validation helpers (server-safe). The lists above are suggestions; a
// participant may also type their own value, which must pass the rules below.
// ---------------------------------------------------------------------------

export const CUSTOM_WORD_MIN = 2;
export const CUSTOM_WORD_MAX = 24;
const CUSTOM_WORD_RE = /^[A-Za-zÀ-ÿ][A-Za-zÀ-ÿ'’ -]*$/;

function squeeze(s: string): string {
  return s.replace(/\s+/g, " ").trim();
}

/** "blue   JAY" -> "Blue Jay", "forget-me-not" -> "Forget-Me-Not". */
export function toTitleCase(s: string): string {
  return squeeze(s)
    .toLowerCase()
    .replace(/(^|[\s-])([a-zà-ÿ])/g, (_m, sep: string, ch: string) => sep + ch.toUpperCase());
}

/** Error message for a custom (typed-in) color/animal/flower, or null if it is acceptable. */
export function customWordError(input: string, label: string): string | null {
  const v = squeeze(input);
  if (v.length < CUSTOM_WORD_MIN) return `Ang ${label} ay dapat may hindi bababa sa ${CUSTOM_WORD_MIN} letra.`;
  if (v.length > CUSTOM_WORD_MAX) return `Ang ${label} ay hanggang ${CUSTOM_WORD_MAX} characters lang.`;
  if (!CUSTOM_WORD_RE.test(v) || /[-'’ ]$/.test(v) || /[-'’ ]{2,}/.test(v)) {
    return `Letra lang ang puwede sa ${label} (puwedeng may space, hyphen o apostrophe — walang numbers o symbols).`;
  }
  if (v.split(" ").length > 3) return `Hanggang tatlong (3) salita lang ang puwede sa ${label}.`;
  return null;
}

function resolveFrom(list: readonly string[], input: string, label: string): string | null {
  const v = squeeze(typeof input === "string" ? input : "");
  if (!v) return null;
  const hit = list.find((x) => x.toLowerCase() === v.toLowerCase());
  if (hit) return hit; // canonical spelling from the list
  return customWordError(v, label) === null ? toTitleCase(v) : null;
}

/** Canonical color (from the list, or a valid custom one in Title Case); null if invalid. */
export function resolveColor(input: string): string | null {
  return resolveFrom(COLORS, input, "color");
}

/** Canonical flower (female) / animal (male); null if invalid. */
export function resolveWord(input: string, sex: string): string | null {
  if (!isValidSex(sex)) return null;
  return resolveFrom(wordsForSex(sex), input, sex === "female" ? "flower" : "animal");
}

export function wordsForSex(sex: string): readonly string[] {
  return sex === "female" ? FLOWERS : ANIMALS;
}

export function isValidSex(sex: string): boolean {
  return sex === "male" || sex === "female";
}

export function isValidColor(color: string): boolean {
  return resolveColor(color) !== null;
}

export function isValidWordForSex(word: string, sex: string): boolean {
  return resolveWord(word, sex) !== null;
}
